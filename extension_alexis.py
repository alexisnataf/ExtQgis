    def displayPoint(self, coord, button):
        coord_depart = self.canvas.mapSettings().destinationCrs()
        if coord_depart.authid() != "EPSG:4326":
            coord_fin = QgsCoordinateReferenceSystem("EPSG:4326")

        coord = QgsCoordinateTransform(coord_depart, coord_fin, QgsProject.instance()).transform(coord)

        x = str(coord.x())
        y = str(coord.y())
        index_special1 = x.find(".")
        index_special2 = y.find(".")
        resX = x[: index_special1 + 1 + 5]
        resY = y[: index_special2 + 1 + 5]
        self.dlg.longitude.setText(resX)
        self.dlg.latitude.setText(resY)    

        if resX != None and resY != None:
            url = f"https://data.geopf.fr/geocodage/reverse?lat={resY}&lon={resX}"
            reponse = requests.get(url)
            if reponse.status_code == 200:
                donnees = reponse.json()
                #QgsMessageLog.logMessage(donnees, "TP", level=0)
                try: 
                    adresse_from_lonlat_name = donnees["features"][0]["properties"]["name"]
                    adresse_from_lonlat_citycode = donnees["features"][0]["properties"]["citycode"]
                    adresse_from_lonlat_city = donnees["features"][0]["properties"]["city"]
                    adresse_from_lonlat = f"{adresse_from_lonlat_name} {adresse_from_lonlat_citycode} {adresse_from_lonlat_city}"
                    self.dlg.adresse.setText(adresse_from_lonlat)
                except (KeyError, IndexError):
                    self.dlg.adresse.setText("adresse introuvable")    
            else:
                self.dlg.adresse.setText("introuvable")
        
        #recuperer la couche selectionne
        nb_metres = self.dlg.metres.text()
        
        try:
            nb_metres = int(nb_metres)
            if nb_metres <= 0:
                raise ValueError
        except ValueError:
            self.iface.messageBar().pushMessage("Error", f"{nb_metres} n'es pas un entier", level=Qgis.Critical)
            return

        couche_selec = self.dlg.listeDesLayers.currentText()
        current_layer = QgsProject.instance().mapLayersByName(couche_selec)
        target_layer = current_layer[0]

        #création de la zone tampon
        crs_source = QgsCoordinateReferenceSystem("EPSG:4326")
        crs_cible = QgsCoordinateReferenceSystem("EPSG:2154")
        transformation = QgsCoordinateTransform(crs_source, crs_cible, QgsProject.instance())
        
        former_point = QgsPointXY(coord.x(), coord.y())
        new_point_lambert93 = transformation.transform(former_point)

        point_clique = QgsGeometry.fromPointXY(new_point_lambert93)
        buffer = point_clique.buffer(int(nb_metres), 30)       

        compteur = 0
        for feature in target_layer.getFeatures():
            mageom = feature.geometry()
            mageom.transform(transformation)
            if buffer.intersects(mageom):
                compteur += 1
        self.dlg.objets.setText(str(compteur))        

        tempo_layers = QgsProject.instance().mapLayersByName("buffer cercle")
        if len(tempo_layers) == 0:
            tempo_Layer = QgsVectorLayer("polygon?crs=epsg:2154", "buffer cercle",  "memory")
            symbole = QgsFillSymbol.createSimple({
    #            'color': '0,0,0,255',
                'style': 'no',
                'outline_color': '0,0,0,255',    
                'outline_width': '0.4',          
                'outline_style': 'solid'                
            })
            renderer = QgsSingleSymbolRenderer(symbole)
            tempo_Layer.setRenderer(renderer)
            QgsProject.instance().addMapLayer(tempo_Layer)
        else:
            tempo_Layer = tempo_layers[0]

        #tempo_Layer.startEditing()

        #pour enlever les buffers precedents
        tempo_Layer.dataProvider().truncate()

        feature_buffer = QgsFeature()
        feature_buffer.setGeometry(buffer)
        tempo_Layer.dataProvider().addFeatures([feature_buffer])
        tempo_Layer.dataProvider().updateExtents()
        tempo_Layer.triggerRepaint()
